"""Prompt for the optional OpenAI-compatible LLM used by the relevance filter.

Writes `data/llm.env`, which `make start` sources. The filter turns on when an
endpoint, model, and key are all present. Leaving the API key blank keeps the
default behavior: search results go straight to fetching.
"""

from __future__ import annotations

import getpass
import os
import sys
from pathlib import Path
from urllib.parse import urlsplit

DEFAULT_BASE_URL = "https://api.openai.com/v1"
DEFAULT_MODEL = "gpt-4o-mini"
DEFAULT_ENV_FILE = "data/llm.env"
TRUE_FLAGS = frozenset({"1", "true", "yes", "on"})


def main() -> None:
    env_file = Path(os.environ.get("LLM_ENV_FILE", DEFAULT_ENV_FILE))
    force = os.environ.get("LLM_CONFIGURE", "").strip().lower() in TRUE_FLAGS
    current = _read_env(env_file)

    if not force and os.environ.get("LLM_API_KEY"):
        print("LLM relevance filter: using LLM_API_KEY from the environment.")
        return
    if not force and current.get("LLM_API_KEY"):
        print(
            "LLM relevance filter: enabled"
            f" ({current.get('LLM_MODEL', DEFAULT_MODEL)}"
            f" at {current.get('LLM_BASE_URL', DEFAULT_BASE_URL)})."
        )
        print(f"  Reconfigure with `make llm-config` or delete {env_file}.")
        return
    if not force and env_file.exists():
        print(
            "LLM relevance filter: disabled (no API key in"
            f" {env_file}). Run `make llm-config` to enable it."
        )
        return
    if not sys.stdin.isatty():
        print(
            "LLM relevance filter: no interactive terminal,"
            f" leaving {env_file} unchanged."
        )
        return

    print("Optional LLM relevance filter (OpenAI-compatible chat completions).")
    print("It drops search results that look unrelated before pages are fetched.")
    print("Press Enter to accept a default. Leave the API key blank to skip it.")

    base_url = _ask_url(
        current.get("LLM_BASE_URL")
        or os.environ.get("LLM_BASE_URL")
        or DEFAULT_BASE_URL
    )
    if base_url is None:
        _write_disabled(env_file)
        return
    model = (
        _ask(
            "  Model",
            current.get("LLM_MODEL")
            or os.environ.get("LLM_MODEL")
            or DEFAULT_MODEL,
        ).strip()
        or DEFAULT_MODEL
    )
    api_key = _ask_secret("  API key").strip()
    if not api_key:
        _write_disabled(env_file, base_url=base_url, model=model)
        return
    _write_enabled(env_file, base_url=base_url, model=model, api_key=api_key)


def _ask_url(default: str) -> str | None:
    for _ in range(3):
        value = _ask("  Endpoint", default).strip()
        if not value:
            return default
        parsed = urlsplit(value)
        if parsed.scheme in ("http", "https") and parsed.netloc:
            return value.rstrip("/")
        print(f"  Endpoint must be an http(s) URL, for example {DEFAULT_BASE_URL}")
    print("LLM relevance filter: invalid endpoint, keeping the current behavior.")
    return None


def _ask(label: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        answer = input(f"{label}{suffix}: ")
    except (EOFError, KeyboardInterrupt):
        print()
        raise SystemExit(1)
    return answer.strip() or default


def _ask_secret(label: str) -> str:
    try:
        return getpass.getpass(f"{label}: ")
    except (EOFError, KeyboardInterrupt):
        print()
        raise SystemExit(1)
    except Exception:
        return _ask(label)


def _write_enabled(
    env_file: Path, *, base_url: str, model: str, api_key: str
) -> None:
    _write_env(
        env_file,
        {
            "LLM_BASE_URL": base_url,
            "LLM_MODEL": model,
            "LLM_API_KEY": api_key,
            "LLM_FILTER_TIMEOUT_S": "10",
        },
    )
    print(f"LLM relevance filter: enabled with {model} at {base_url}.")


def _write_disabled(
    env_file: Path, *, base_url: str | None = None, model: str | None = None
) -> None:
    values: dict[str, str] = {}
    if base_url:
        values["LLM_BASE_URL"] = base_url
    if model:
        values["LLM_MODEL"] = model
    _write_env(env_file, values)
    print("LLM relevance filter: disabled; results go straight to fetching.")


def _write_env(env_file: Path, values: dict[str, str]) -> None:
    env_file.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by `make llm-config`.",
        "# The relevance filter is on only when LLM_BASE_URL, LLM_MODEL, and",
        "# LLM_API_KEY are all set. Delete this file to be asked again.",
        *(f"{key}={_quote(value)}" for key, value in values.items()),
    ]
    env_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    env_file.chmod(0o600)


def _read_env(env_file: Path) -> dict[str, str]:
    try:
        text = env_file.read_text(encoding="utf-8")
    except OSError:
        return {}
    values: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, raw = stripped.partition("=")
        values[key.strip()] = _unquote(raw.strip())
    return values


def _quote(value: str) -> str:
    return "'" + value.replace("'", "'\\''") + "'"


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("'\\''", "'")
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1]
    return value


if __name__ == "__main__":
    main()
